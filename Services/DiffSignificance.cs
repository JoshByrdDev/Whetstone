using System.Text.RegularExpressions;

namespace Whetstone.Services;

/// <summary>How much of a human's attention one changed file has earned.</summary>
public enum DiffTier
{
    /// <summary>Read this one. Logic, schema, or a query that was rewritten rather than extended.</summary>
    Major,
    /// <summary>Real but ordinary. Worth a glance.</summary>
    Normal,
    /// <summary>Mechanical or generated. Present, folded away, almost never wrong.</summary>
    Minor,
}

/// <summary>
/// A file's verdict. <paramref name="Reasons"/> is what actually fired, in the order it fired, so
/// the badge on screen is the explanation and not a decoration.
/// </summary>
public record DiffVerdict(int Score, DiffTier Tier, IReadOnlyList<string> Reasons);

/// <summary>
/// Ranks the files in a diff by how much they are worth reading.
///
/// <para>
/// The problem this solves is specific and comes from real tickets: adding one field to a domain
/// concept touches fifteen files, and fourteen of them are the same line copied into a proto, an
/// enum, a view model and a generated client. Line counts rank those ABOVE the three-line change to
/// an inline SQL query that is the only place the ticket could actually be wrong. Sorting by size,
/// or by path, buries the review in the boilerplate it generated.
/// </para>
///
/// <para>
/// So the ranking is by shape, not by volume. Three things push a file up: control flow and new
/// declarations (logic that did not exist before), schema statements (a migration is the one change
/// that cannot be rolled back by editing code), and SQL that was <b>rewritten</b> rather than
/// appended — an existing query whose meaning changed is the highest-risk edit per line in this
/// codebase. One thing pushes a file down hard: every changed line being a member declaration, an
/// import, or generated output, which is exactly what the fourteen boilerplate files are made of.
/// </para>
///
/// <para>
/// Being wrong here is asymmetric, and the tiers are set accordingly. A boring file promoted to
/// Major costs a few seconds of scrolling. A real change demoted to Minor is a bug that ships
/// because it was folded shut — so anything with a single line of control flow, a declaration or a
/// query in it can never be demoted on size alone.
/// </para>
/// </summary>
public static class DiffSignificance
{
    /// <summary>What a path says about a file before anything is read out of it.</summary>
    private enum PathKind { Source, Generated, Migration, Test, Docs, Config }

    // Weights, applied to the content score. Generated output is near-zeroed rather than excluded:
    // a hand-edit to a generated file is a real (and alarming) thing, so it stays rankable.
    private static double WeightOf(PathKind k) => k switch
    {
        PathKind.Generated => 0.05,
        PathKind.Docs => 0.25,
        PathKind.Config => 0.30,
        PathKind.Test => 0.60,
        PathKind.Migration => 1.40,
        _ => 1.0,
    };

    /// <summary>Files whose first lines say a tool wrote them. Cheaper and far more durable than a path list.</summary>
    public static readonly string[] GeneratedMarkers =
    {
        "<auto-generated", "DO NOT EDIT", "@generated", "Code generated by",
        "This code was generated by", "generated by Openapi Generator",
    };

    /// <summary>
    /// Judge one file.
    /// <paramref name="body"/> is its hunks only (everything from the first <c>@@</c>), so the
    /// <c>---</c>/<c>+++</c> headers can never be counted as a wholesale rewrite.
    /// </summary>
    public static DiffVerdict Judge(
        string path,
        int added,
        int removed,
        bool binary,
        string body,
        bool markedGenerated = false,
        IReadOnlyList<string>? noiseGlobs = null)
    {
        var reasons = new List<string>();
        var kind = Classify(path, markedGenerated, noiseGlobs);

        if (binary) return new DiffVerdict(0, DiffTier.Minor, new[] { "binary" });
        if (kind == PathKind.Generated) return new DiffVerdict(0, DiffTier.Minor, new[] { "generated" });

        // A rename git resolved with no content change: nothing was written, only moved.
        if (added == 0 && removed == 0)
            return new DiffVerdict(0, DiffTier.Minor, new[] { "renamed" });

        var c = Count(body);

        // Same lines out and back in — a reformat, an indent change, a reorder. Nothing to review.
        if (c.FormattingOnly)
            return new DiffVerdict(0, DiffTier.Minor, new[] { "formatting" });

        // Serialised data is not code, and its keywords are not keywords. A Postman collection full
        // of request bodies trips SELECT and return on plain strings and would otherwise outrank the
        // migration beside it. So for data and prose the code signals are struck out entirely and
        // the file is ranked on size alone — visible, never top billing.
        var dataOnly = kind is PathKind.Docs or PathKind.Config;
        if (dataOnly) c = c.WithoutCodeSignals();

        var substantive = c.ControlFlow > 0 || c.Declarations > 0 || c.Sql > 0;

        // The boilerplate case, and the whole reason this class exists: every line that carries any
        // meaning is a member declaration or an import. A new enum entry, a new proto field, a new
        // auto-property on a view model. Fifteen of these per ticket, none of them ever wrong.
        if (!substantive && c.Meaningful > 0 && c.Meaningful == c.Members + c.Imports)
        {
            reasons.Add(c.Members >= c.Imports ? "list entries" : "imports");
            AddPathReason(reasons, kind);
            return new DiffVerdict(Math.Min(5, c.Meaningful), DiffTier.Minor, reasons);
        }

        var churn = Math.Min(c.Added, c.Removed);
        var total = c.Added + c.Removed;

        var raw =
            4.0 * Math.Min(c.ControlFlow, 30) +
            5.0 * Math.Min(c.Declarations, 20) +
            5.0 * Math.Min(c.Sql, 30) +
            8.0 * Math.Min(c.Ddl, 15) +
            3.0 * Math.Min(churn, 50) +
            2.0 * Math.Min(c.Hunks, 15) +
            Math.Min(total, 300) / 5.0;

        var score = (int)Math.Round(raw * WeightOf(kind));

        // ---- reasons, strongest first ----
        if (kind == PathKind.Migration) reasons.Add("migration");
        if (c.Ddl > 0) reasons.Add("schema change");
        if (c.Sql > 0 && churn > 0) reasons.Add("query changed");
        else if (c.Sql > 0) reasons.Add("sql");
        if (c.ControlFlow > 0) reasons.Add("control flow");
        if (c.Declarations > 0) reasons.Add("new declarations");
        if (churn >= 8) reasons.Add("rewritten");
        if (c.Hunks >= 5) reasons.Add("scattered");
        if (total >= 150) reasons.Add("large");
        if (removed > 0 && added == 0) reasons.Add("deleted");
        AddPathReason(reasons, kind);
        // Never leave a file with no explanation next to files that have one — an empty badge row
        // reads as "not assessed" rather than as "assessed, and ordinary".
        if (reasons.Count == 0) reasons.Add(churn > 0 ? "edited" : "added");

        // ---- tier ----
        // A migration or a DDL statement is Major regardless of size: it is the one change in a
        // ticket that a later code edit cannot undo.
        //
        // "query changed" is here for the case line counts get most wrong — three lines inside an
        // existing SQL string, where the diff is tiny and the blast radius is not.
        var tier =
            // Data and prose cap at Normal however big they get: nothing in a JSON fixture is worth
            // outranking a migration, and its size is the only honest thing known about it.
            dataOnly
                ? (score >= 12 ? DiffTier.Normal : DiffTier.Minor)
            : kind == PathKind.Migration || c.Ddl > 0 || (c.Sql > 0 && churn > 0) || score >= 45
                ? DiffTier.Major
            // Demotion on size alone is only allowed when nothing meaningful is in the file. One
            // line of control flow keeps it visible, because that is where the bug would be.
            : !substantive && score < 12
                ? DiffTier.Minor
                : DiffTier.Normal;

        return new DiffVerdict(score, tier, reasons);
    }

    private static void AddPathReason(List<string> reasons, PathKind kind)
    {
        var word = kind switch
        {
            PathKind.Test => "tests",
            PathKind.Docs => "docs",
            PathKind.Config => "config",
            _ => null,
        };
        if (word is not null) reasons.Add(word);
    }

    // ---- path ---------------------------------------------------------------

    private static PathKind Classify(string path, bool markedGenerated, IReadOnlyList<string>? noiseGlobs)
    {
        var p = path.Replace('\\', '/');
        var file = p[(p.LastIndexOf('/') + 1)..];
        var lower = p.ToLowerInvariant();
        var lowerFile = file.ToLowerInvariant();

        if (markedGenerated) return PathKind.Generated;
        if (noiseGlobs is not null && noiseGlobs.Any(g => GlobMatch(g, p))) return PathKind.Generated;

        if (LockFiles.Contains(lowerFile)) return PathKind.Generated;
        if (GeneratedSuffixes.Any(s => lowerFile.EndsWith(s, StringComparison.Ordinal))) return PathKind.Generated;
        if (HasSegment(lower, GeneratedSegments)) return PathKind.Generated;

        // Extension beats folder for serialised data and prose. A .json under tests/ is a fixture,
        // not a test — judging it by its folder is how a 377-line Postman collection ends up ranked
        // as code because its request bodies contain the word SELECT.
        if (DocSuffixes.Any(s => lowerFile.EndsWith(s, StringComparison.Ordinal))) return PathKind.Docs;
        if (ConfigSuffixes.Any(s => lowerFile.EndsWith(s, StringComparison.Ordinal))) return PathKind.Config;
        if (ConfigFiles.Contains(lowerFile)) return PathKind.Config;

        // EF pairs every migration with a .Designer.cs and one shared ModelSnapshot.cs, both machine
        // written. The migration beside them is hand-written and is the point of the whole change.
        if (HasSegment(lower, MigrationSegments) || lower.Contains("/db/migrate/", StringComparison.Ordinal))
            return PathKind.Migration;

        if (HasSegment(lower, TestSegments)) return PathKind.Test;
        if (TestSuffixes.Any(s => lowerFile.EndsWith(s, StringComparison.Ordinal))) return PathKind.Test;

        return PathKind.Source;
    }

    private static readonly HashSet<string> LockFiles = new(StringComparer.Ordinal)
    {
        "package-lock.json", "yarn.lock", "pnpm-lock.yaml", "cargo.lock", "composer.lock",
        "poetry.lock", "go.sum", "packages.lock.json", "gemfile.lock",
    };

    private static readonly string[] GeneratedSuffixes =
    {
        ".g.cs", ".generated.cs", ".designer.cs", ".g.i.cs", ".feature.cs",
        "modelsnapshot.cs", "_pb2.py", "_pb2_grpc.py", ".pb.go", ".pb.cc", ".pb.h",
        ".min.js", ".min.css", ".map", ".snap", ".d.ts",
    };

    private static readonly string[] GeneratedSegments =
    {
        "node_modules", "obj", "bin", "dist", "vendor", ".next", "__pycache__", "coverage",
    };

    private static readonly string[] MigrationSegments = { "migrations", "migration" };

    private static readonly string[] TestSegments = { "test", "tests", "__tests__", "spec", "e2e" };

    private static readonly string[] TestSuffixes =
    {
        "tests.cs", "test.cs", ".test.ts", ".test.tsx", ".test.js", ".test.jsx",
        ".spec.ts", ".spec.tsx", ".spec.js", "_test.go", "_test.py",
    };

    private static readonly string[] DocSuffixes = { ".md", ".mdx", ".rst", ".txt", ".adoc" };

    private static readonly string[] ConfigSuffixes =
    {
        ".json", ".yml", ".yaml", ".toml", ".ini", ".xml", ".config", ".props", ".targets",
        ".csv", ".editorconfig", ".gitignore", ".gitattributes", ".sln", ".http",
    };

    private static readonly HashSet<string> ConfigFiles = new(StringComparer.Ordinal)
    {
        "dockerfile", "makefile", "procfile", ".dockerignore", ".env", ".npmrc", ".nvmrc",
    };

    private static bool HasSegment(string lowerPath, string[] segments)
    {
        foreach (var s in lowerPath.Split('/'))
            if (segments.Contains(s)) return true;
        return false;
    }

    /// <summary>
    /// Minimal glob for the per-project noise list: <c>*</c> stops at a separator, <c>**</c> does
    /// not. Enough for "everything under this folder" and "every file with this suffix", which is
    /// all these entries are ever used for.
    /// </summary>
    public static bool GlobMatch(string glob, string path)
    {
        if (string.IsNullOrWhiteSpace(glob)) return false;
        var pattern = "^" + Regex.Escape(glob.Replace('\\', '/'))
            .Replace(@"\*\*/", "(?:.*/)?")
            .Replace(@"\*\*", ".*")
            .Replace(@"\*", "[^/]*")
            .Replace(@"\?", "[^/]") + "$";
        return Regex.IsMatch(path.Replace('\\', '/'), pattern, RegexOptions.IgnoreCase, TimeSpan.FromSeconds(1));
    }

    // ---- content ------------------------------------------------------------

    private record Counts(
        int Added, int Removed, int Hunks, int Meaningful,
        int ControlFlow, int Declarations, int Sql, int Ddl, int Members, int Imports,
        bool FormattingOnly)
    {
        /// <summary>The same file judged as data: keyword hits inside strings are not code.</summary>
        public Counts WithoutCodeSignals() =>
            this with { ControlFlow = 0, Declarations = 0, Sql = 0, Ddl = 0 };
    }

    private static Counts Count(string body)
    {
        int added = 0, removed = 0, hunks = 0, meaningful = 0;
        int control = 0, decls = 0, sql = 0, ddl = 0, members = 0, imports = 0;

        // Multisets of trimmed text, to spot a file whose lines all went out and came back.
        var outgoing = new Dictionary<string, int>(StringComparer.Ordinal);
        var incoming = new Dictionary<string, int>(StringComparer.Ordinal);

        foreach (var raw in body.Split('\n'))
        {
            var line = raw.TrimEnd('\r');
            if (line.Length == 0) continue;
            if (line.StartsWith("@@", StringComparison.Ordinal)) { hunks++; continue; }

            var sign = line[0];
            if (sign != '+' && sign != '-') continue;

            var text = line[1..].Trim();
            if (sign == '+') { added++; Bump(incoming, text); } else { removed++; Bump(outgoing, text); }
            if (text.Length == 0) continue;

            switch (ClassifyLine(text))
            {
                case LineKind.Trivial: break;
                case LineKind.Import: imports++; meaningful++; break;
                case LineKind.Member: members++; meaningful++; break;
                case LineKind.Ddl: ddl++; sql++; meaningful++; break;
                case LineKind.Sql: sql++; meaningful++; break;
                case LineKind.ControlFlow: control++; meaningful++; break;
                case LineKind.Declaration: decls++; meaningful++; break;
                default: meaningful++; break;
            }
        }

        var formattingOnly = added > 0 && removed > 0 && SameMultiset(incoming, outgoing);
        return new Counts(added, removed, hunks, meaningful, control, decls, sql, ddl, members, imports, formattingOnly);

        static void Bump(Dictionary<string, int> d, string k) => d[k] = d.TryGetValue(k, out var n) ? n + 1 : 1;
    }

    private static bool SameMultiset(Dictionary<string, int> a, Dictionary<string, int> b)
    {
        if (a.Count != b.Count) return false;
        foreach (var (k, v) in a)
            if (!b.TryGetValue(k, out var other) || other != v) return false;
        return true;
    }

    private enum LineKind { Trivial, Import, Member, Sql, Ddl, ControlFlow, Declaration, Other }

    /// <summary>
    /// What one changed line is. Order matters and is the whole trick:
    /// <b>Member is tested before Declaration</b>, so <c>public bool? Enroller { get; set; }</c>
    /// reads as one more field on a model rather than as new API surface — that single ordering is
    /// what separates the fourteen boilerplate files from the one worth reading.
    /// </summary>
    private static LineKind ClassifyLine(string text)
    {
        if (TrivialRx.IsMatch(text)) return LineKind.Trivial;
        if (ImportRx.IsMatch(text)) return LineKind.Import;
        if (MemberRx.IsMatch(text)) return LineKind.Member;
        if (DdlRx.IsMatch(text)) return LineKind.Ddl;
        if (SqlRx.IsMatch(text)) return LineKind.Sql;
        if (ControlFlowRx.IsMatch(text)) return LineKind.ControlFlow;
        if (DeclarationRx.IsMatch(text)) return LineKind.Declaration;
        return LineKind.Other;
    }

    private const RegexOptions Opts = RegexOptions.Compiled | RegexOptions.CultureInvariant;
    private static readonly TimeSpan Limit = TimeSpan.FromSeconds(1);

    /// <summary>Braces, comments, attributes, decorators — punctuation the reviewer never reads.</summary>
    private static readonly Regex TrivialRx = new(
        @"^(?:[{}()\[\];,]+|//.*|/\*.*|\*.*|#(?!include|define).*|--\s.*|<!--.*|@\w+(?:\(.*\))?|\[[^\]]*\])$",
        Opts, Limit);

    private static readonly Regex ImportRx = new(
        @"^(?:using\s+[\w.=\s]+;|import\s|export\s+\*|export\s+\{[^}]*\}\s+from\b|from\s+[\w.]+\s+import\b|#include\b|require\s*\()",
        Opts, Limit);

    /// <summary>
    /// One more field on a thing that already exists: a C# auto-property, an enum member, a proto
    /// field, a TypeScript interface property, a constant. This is the shape of the boring file.
    /// </summary>
    private static readonly Regex MemberRx = new(
        @"^(?:(?:public|private|protected|internal|static|virtual|override|abstract|sealed|required|readonly|const|new|partial|repeated|optional|export|declare)\s+)*(?:" +
        // auto-property:  public bool? Enroller { get; set; }
        @"[\w?<>\[\],.]+\s+\w+\s*\{\s*get;\s*(?:(?:private|protected|internal)\s+)?(?:set|init);?\s*\}(?:\s*=\s*[^;]+;)?" +
        // typed field, with or without an initializer:  google.protobuf.BoolValue Enroller = 36;
        @"|[\w?<>\[\],.]+\s+\w+\s*(?:=\s*[^;{}]+)?;" +
        // enum member:  Enroller = 50,
        @"|\w+\s*(?:=\s*[^,;{}]+)?,?" +
        // TS/interface property:  enroller?: boolean;
        @"|\w+\??\s*:\s*[^;{}=]+[;,]?" +
        @")$",
        Opts, Limit);

    /// <summary>
    /// Statements that change the database's shape. Weighted hardest, and an automatic promotion:
    /// it is the one edit in a ticket that shipping cannot be undone by editing code.
    /// </summary>
    private static readonly Regex DdlRx = new(
        @"\b(?:CREATE|ALTER|DROP|TRUNCATE)\s+(?:TABLE|INDEX|VIEW|SCHEMA|PROCEDURE|PROC|FUNCTION|TYPE|CONSTRAINT|DATABASE)\b|\bADD\s+(?:COLUMN|CONSTRAINT)\b|\bmigrationBuilder\.\w+",
        Opts | RegexOptions.IgnoreCase, Limit);

    private static readonly Regex SqlRx = new(
        @"\b(?:SELECT|INSERT\s+INTO|UPDATE\s+\w|DELETE\s+FROM|FROM\s+\w|(?:INNER|LEFT|RIGHT|OUTER|CROSS)?\s*JOIN\s+\w|WHERE\s+\w|GROUP\s+BY|ORDER\s+BY|UNPIVOT|PIVOT|MERGE\s+INTO|EXEC\s+\w|ISNULL\s*\()",
        Opts | RegexOptions.IgnoreCase, Limit);

    private static readonly Regex ControlFlowRx = new(
        @"\b(?:if|else|for|foreach|while|do|switch|case|try|catch|finally|throw|return|await|yield|break|continue)\b",
        Opts, Limit);

    private static readonly Regex DeclarationRx = new(
        @"\b(?:class|interface|record|struct|enum|namespace)\s+\w" +
        @"|^(?:(?:public|private|protected|internal|static|async|override|virtual|abstract|sealed|partial|extern|unsafe|new)\s+)+[\w?<>\[\],.]+\s+\w+\s*\(" +
        @"|\bfunction\s+\w+\s*\(" +
        @"|\b(?:export\s+)?(?:const|let|var)\s+\w+[^=]*=\s*(?:async\s*)?\([^)]*\)\s*(?::[^=]+)?=>" +
        @"|\bdef\s+\w+\s*\(" +
        @"|\bfunc\s+\w*\s*\(",
        Opts, Limit);
}
