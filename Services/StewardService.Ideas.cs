using System.Text;
using System.Text.RegularExpressions;
using Microsoft.EntityFrameworkCore;
using Whetstone.Models;

namespace Whetstone.Services;

/// <summary>An idea the steward proposes to the owner: the slice file, and its whole text.</summary>
public record StewardIdeaProposal(string File, string Text);

/// <summary>
/// A plan is its slices (docs/plans-as-slices.md, section 1): ideas the owner writes, drafted one
/// at a time when their turn comes, agreed, built, released. This is the part of that the board
/// keeps: the plan as read, generated rather than maintained; the idea a steward proposes and the
/// owner commits; and the agreed slice whose number or file has moved.
/// </summary>
public partial class StewardService
{
    /// <summary>The options every idea proposal is answered by. The first commits it.</summary>
    public const string CommitIdea = "Commit this idea", LeaveIdeas = "Leave the ideas as they are";

    /// <summary>
    /// Why a proposed idea cannot be committed as asked, or null when it can. An idea comes after
    /// the last agreed slice, and replaces only an idea: a draft is the steward's to revise, and an
    /// agreed slice is never touched.
    /// </summary>
    private string? IdeaRefusal(StewardPlan p, IReadOnlyList<PlanUnit> plan, StewardIdeaProposal idea)
    {
        var name = idea.File?.Trim() ?? "";
        var m = Regex.Match(name, p.UnitFile, RegexOptions.IgnoreCase);
        if (!m.Success || name.Contains('/') || name.Contains('\\') || !int.TryParse(m.Groups[1].Value, out var number))
            return "Name the idea's file the way the plan's slices are named, number first, with no folder.";
        var lastAgreed = plan.Where(u => u.Agreed).Select(u => u.Number).DefaultIfEmpty(0).Max();
        if (number <= lastAgreed) return $"Slice {lastAgreed} is agreed, so an idea is numbered after it. An agreed slice's number never changes.";
        var path = $"{p.UnitsDir}/{name}";
        var unit = TicketGitService.ReadUnit(p, number, path, idea.Text ?? "");
        if (!unit.Idea) return "Its status line must say it is an idea (**Status: idea.**): a draft is written with steward_draft_unit, and only from an idea.";
        if (plan.FirstOrDefault(u => string.Equals(u.File, path, StringComparison.OrdinalIgnoreCase)) is { Idea: false } there)
            return $"{there.File} is {(there.Agreed ? "agreed" : "a draft")}, not an idea: an idea replaces only an idea.";
        return null;
    }

    /// <summary>Commit an idea the owner said yes to. Null when it is committed, else why not.</summary>
    private async Task<string?> CommitIdeaAsync(ProjectConfig cfg, StewardQuestion q, CancellationToken ct)
    {
        var p = cfg.Steward.Plan;
        var plan = await _git.PlanAsync(cfg.Name, ct);
        var idea = new StewardIdeaProposal(q.ProposedFile!, q.ProposedText!);
        if (IdeaRefusal(p, plan, idea) is { } no) return $"The idea was not committed: {no}";
        var (_, _, refusal) = await _git.CommitFileAsync(cfg.Name, $"{p.UnitsDir}/{idea.File}", idea.Text,
            $"An idea, {idea.File}, committed by its owner (answering {q.Key})", ct);
        return refusal;
    }

    // ---- the plan as read ----------------------------------------------------------------------

    /// <summary>
    /// The plan as a person reads it, generated and never maintained: the charter, the decisions
    /// in force for the whole project, and every slice in order - built and released ones folded to
    /// their title, story and status, the one being worked in full, ideas as their paragraph.
    /// </summary>
    public async Task<string?> PlanAsReadAsync(string projectKey, string? planKey = null, CancellationToken ct = default)
    {
        if (Config(projectKey) is not { } cfg) return null;
        var which = planKey is null ? cfg.Steward.Plan : cfg.Steward.PlanByKey(planKey);
        if (which is null || !which.Configured) return null;
        var working = ReferenceEquals(which, cfg.Steward.Plan);
        var plan = await _git.PlanOfAsync(projectKey, which, ct);
        var states = await StatesAsync(projectKey, which.Key, ct);
        var mine = (await _tickets.ListAsync(projectKey, null)).Where(t => (t.PlanKey ?? "") == which.Key).ToList();
        var rows = await _db.StewardUnits.AsNoTracking().Where(u => u.ProjectKey == projectKey && u.Plan == which.Key).ToListAsync(ct);
        var current = working ? StewardProgress.Current(plan, states)?.Number : null;

        var sb = new StringBuilder($"# {which.DisplayName}\n\n")
            .Append("> The plan as read: the charter, the decisions in force for the whole project, and every slice in order. ")
            .Append("Generated by the ticket board from those; edits here are overwritten.\n");

        if (which.Charter.Length > 0 && await _git.FileAtBaseAsync(projectKey, which.Charter, ct) is { } charter)
            sb.Append("\n## The charter\n\n").Append(Demote(Regex.Replace(charter.Replace("\r\n", "\n"), @"\A#\s+[^\n]*\n+", "")).Trim()).Append('\n');

        await EnsureRegisterAsync(cfg, ct);
        var all = await RegisterAsync(projectKey, track: false, ct);
        var map = ReplacedIndex(all);
        var whole = all.Where(d => d.PlanUnit is null && StatusOf(d, map).Name is InForce or Provisional).ToList();
        if (whole.Count > 0)
            sb.Append("\n## Decided for the whole project\n\n")
              .Append(string.Join("\n", whole.Select(d => $"- **#{d.Number}** {d.Rule.Replace("\n", " ")}{(d.Provisional ? " *(provisional)*" : "")}")))
              .Append('\n');

        sb.Append("\n## The slices\n");
        foreach (var u in plan)
        {
            var p = StewardProgress.For(u, states, mine);
            var row = rows.FirstOrDefault(r => r.Unit == u.Number);
            var built = u.Agreed && p.Outcomes > 0 && p.Done == p.Outcomes;
            var stage = row?.ReleasedAt is not null ? "released" : built ? "built"
                : u.Agreed ? u.Number == current ? "building" : "agreed"
                : u.Draft ? "draft" : u.Idea ? "idea" : "not agreed";
            sb.Append($"\n### {u.Number}. {Regex.Replace(TicketGitService.UnitTitle(u), @"^(?:unit|slice)\s+\d+\s*[:.-]\s*", "", RegexOptions.IgnoreCase)} - {stage}\n\n");
            if (stage == "building")
                sb.Append(Demote(Demote(Regex.Replace(u.Text.Replace("\r\n", "\n"), @"\A#\s+[^\n]*\n+", ""))).Trim()).Append('\n');
            else if (u.Idea)
                sb.Append(SliceStory.IdeaParagraph(u.Text)).Append('\n');
            else
                sb.Append(SliceStory.Find(u.Text)?.Text is { Length: > 0 } story ? story : SliceStory.IdeaParagraph(u.Text)).Append('\n');
        }
        return sb.ToString();
    }

    private static string Demote(string markdown) => Regex.Replace(markdown, @"^(#+)(\s)", "#$1$2", RegexOptions.Multiline);

    /// <summary>
    /// Write the plan as read out to the repo, when the plan names a file for it. Only when a slice
    /// changes stage - agreed, drafted, released, an idea committed - so the base branch's history is
    /// not one commit per answer. Best-effort, like the decisions file.
    /// </summary>
    private async Task<string?> WriteReadableAsync(ProjectConfig cfg, CancellationToken ct)
    {
        var file = cfg.Steward.Plan.Readable;
        if (file.Length == 0 || cfg.StewardMode is StewardMode.Off or StewardMode.Propose) return null;
        if (await PlanAsReadAsync(cfg.Name, null, ct) is not { } text) return null;
        var (sha, unchanged, refusal) = await _git.CommitFileAsync(cfg.Name, file, text, "The plan as read, written out by the board", ct);
        return refusal is not null ? $"not written to {file}: {refusal}" : unchanged ? null : $"written to {file} at {sha}";
    }

    // ---- an agreed slice that moved -------------------------------------------------------------

    /// <summary>
    /// Agreed slices whose number or file has changed since they were agreed, by number, with what
    /// is wrong. Remembers the file of every agreed slice it has not seen before, which is how a
    /// slice agreed by hand in its file is held to its number too.
    /// </summary>
    private async Task<Dictionary<int, string>> MovedSlicesAsync(string projectKey, StewardPlan p, IReadOnlyList<PlanUnit> plan, CancellationToken ct)
    {
        var rows = await _db.StewardUnits.Where(u => u.ProjectKey == projectKey && u.Plan == p.Key).ToListAsync(ct);
        var moved = new Dictionary<int, string>();
        var changed = false;
        foreach (var u in plan.Where(u => u.Agreed))
        {
            var row = rows.FirstOrDefault(r => r.Unit == u.Number);
            if (row is null) { _db.StewardUnits.Add(row = new StewardUnit { ProjectKey = projectKey, Plan = p.Key, Unit = u.Number }); rows.Add(row); }
            if (row.AgreedFile is null) { row.AgreedFile = u.File; changed = true; }
        }
        foreach (var row in rows.Where(r => r.AgreedFile is not null))
        {
            var now = plan.FirstOrDefault(u => u.Number == row.Unit);
            if (now is null || !string.Equals(now.File, row.AgreedFile, StringComparison.OrdinalIgnoreCase) || !now.Agreed)
                moved[row.Unit] = now is null
                    ? $"Slice {row.Unit} was agreed as {row.AgreedFile}, and no file has that number now. Tickets and outcomes carry its number: put it back."
                    : !now.Agreed ? $"Slice {row.Unit} was agreed, and {now.File} no longer says so."
                    : $"Slice {row.Unit} was agreed as {row.AgreedFile}, and is {now.File} now. An agreed slice's file and number are fixed: tickets and outcomes carry them.";
        }
        if (changed) await _db.SaveChangesAsync(ct);
        return moved;
    }
}
